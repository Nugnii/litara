    /// Язык интерфейса: выбранный в настройках, иначе язык системы, иначе английский.
    static var current: Language {
        if let chosen = Settings.interfaceLanguage { return chosen }
        let system = Locale.preferredLanguages.first.map { String($0.prefix(2)) } ?? "en"
        return Language(rawValue: system) ?? .en
    }

    static func text(_ key: Key, _ language: Language = current) -> String {
        table[key]?[language] ?? table[key]?[.en] ?? "\(key)"
    }

    /// Что делает хоткей — строкой меню и в настройках.
    static func hint(_ action: HotkeyAction, _ language: Language = current) -> String {
        switch action {
        case .fix: text(.hintFix, language)
        case .nextLayout: text(.hintLayout, language)
        case .changeCase: text(.hintCase, language)
        case .transliterate: text(.hintTranslit, language)
        case .toggleAutoCorrect: text(.hintToggleAuto, language)
        }
    }

